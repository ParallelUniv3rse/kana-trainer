"""Builds src/data/kana.js (kana table, course units, KanjiVG stroke paths)
and src/fonts/kana.woff2 (Noto Sans JP cut down to what the app shows).

Run from the project root: python3 build/build_data.py
Needs build/kvg/*.svg (KanjiVG) and build/NotoSansJP.ttf.
"""
import json, re, os

# ---- Kana table -----------------------------------------------------------
# Each row: (hiragana, romaji, [accepted alternatives])
BASIC = [
    ("vowels", "Vowels", [("あ","a"),("い","i"),("う","u"),("え","e"),("お","o")]),
    ("k", "K row", [("か","ka"),("き","ki"),("く","ku"),("け","ke"),("こ","ko")]),
    ("s", "S row", [("さ","sa"),("し","shi",["si"]),("す","su"),("せ","se"),("そ","so")]),
    ("t", "T row", [("た","ta"),("ち","chi",["ti"]),("つ","tsu",["tu"]),("て","te"),("と","to")]),
    ("n", "N row", [("な","na"),("に","ni"),("ぬ","nu"),("ね","ne"),("の","no")]),
    ("h", "H row", [("は","ha"),("ひ","hi"),("ふ","fu",["hu"]),("へ","he"),("ほ","ho")]),
    ("m", "M row", [("ま","ma"),("み","mi"),("む","mu"),("め","me"),("も","mo")]),
    ("y", "Y row", [("や","ya"),("ゆ","yu"),("よ","yo")]),
    ("r", "R row", [("ら","ra"),("り","ri"),("る","ru"),("れ","re"),("ろ","ro")]),
    ("w", "W row and n", [("わ","wa"),("を","wo",["o"]),("ん","n",["nn"])]),
    ("gz", "G and Z rows", [("が","ga"),("ぎ","gi"),("ぐ","gu"),("げ","ge"),("ご","go"),
                            ("ざ","za"),("じ","ji",["zi"]),("ず","zu"),("ぜ","ze"),("ぞ","zo")]),
    ("dbp", "D, B and P rows", [("だ","da"),("ぢ","ji",["di"]),("づ","zu",["du"]),("で","de"),("ど","do"),
                                ("ば","ba"),("び","bi"),("ぶ","bu"),("べ","be"),("ぼ","bo"),
                                ("ぱ","pa"),("ぴ","pi"),("ぷ","pu"),("ぺ","pe"),("ぽ","po")]),
]

def combos(rows):
    out = []
    for base, stem, alts in rows:
        for small, v in (("ゃ","a"),("ゅ","u"),("ょ","o")):
            out.append((base+small, stem+v, [a+v for a in alts]))
    return out

COMBO1 = combos([("き","ky",[]),("し","sh",["sy"]),("ち","ch",["ty","cy"]),("に","ny",[]),("ひ","hy",[])])
COMBO2 = combos([("み","my",[]),("り","ry",[]),("ぎ","gy",[]),("じ","j",["zy","jy"]),("び","by",[]),("ぴ","py",[])])

UNITS_H = BASIC + [("c1", "Combined sounds 1", COMBO1), ("c2", "Combined sounds 2", COMBO2)]

def to_kata(s):
    return "".join(chr(ord(c) + 0x60) if 0x3041 <= ord(c) <= 0x3096 else c for c in s)

def norm(row):
    k, r = row[0], row[1]
    alts = row[2] if len(row) > 2 else []
    return k, r, alts

def chunk(items, size=3):
    """Lesson groups of 3 new characters; a trailing single joins the previous group."""
    groups = [items[i:i+size] for i in range(0, len(items), size)]
    if len(groups) > 1 and len(groups[-1]) == 1:
        groups[-2] += groups.pop()
    return groups

items, units = {}, []
for script, prefix in (("hiragana", "h"), ("katakana", "k")):
    for uid, title, rows in UNITS_H:
        ids = []
        for row in rows:
            k, r, alts = norm(row)
            if script == "katakana":
                k = to_kata(k)
            iid = f"{prefix}:{k}"
            items[iid] = {"id": iid, "kana": k, "romaji": r, "alts": alts, "script": script}
            ids.append(iid)
        units.append({
            "id": f"{prefix}-{uid}", "script": script, "title": title,
            "lessons": [{"id": f"{prefix}-{uid}-{i+1}", "new": g} for i, g in enumerate(chunk(ids))]
                       + [{"id": f"{prefix}-{uid}-review", "new": [], "review": ids}],
        })

# ---- Strokes from KanjiVG -------------------------------------------------
strokes = {}
chars = sorted({c for it in items.values() for c in it["kana"]})
for c in chars:
    fn = f"build/kvg/{ord(c):05x}.svg"
    svg = open(fn, encoding="utf-8").read()
    paths = re.findall(r'<path id="kvg:[0-9a-f]+-s(\d+)"[^>]*\sd="([^"]+)"', svg)
    paths.sort(key=lambda p: int(p[0]))
    strokes[c] = [d for _, d in paths]
    assert strokes[c], c

os.makedirs("src/data", exist_ok=True)
with open("src/data/kana.js", "w", encoding="utf-8") as f:
    f.write("// Generated by build/build_data.py. Stroke paths from KanjiVG (CC BY-SA 3.0, Ulrich Apel).\n")
    f.write("export const ITEMS = " + json.dumps(items, ensure_ascii=False) + ";\n")
    f.write("export const UNITS = " + json.dumps(units, ensure_ascii=False) + ";\n")
    f.write("export const STROKES = " + json.dumps(strokes, ensure_ascii=False, separators=(",", ":")) + ";\n")

print(len(items), "items,", len(units), "units,", sum(len(u["lessons"]) for u in units), "lessons,", len(strokes), "stroke sets")

# ---- Font subset ----------------------------------------------------------
from fontTools import subset
os.makedirs("src/fonts", exist_ok=True)
text = "".join(chars) + "".join(chr(c) for c in range(0x20, 0x7F)) + "ー・「」、。…’“”–—×✓★♥←→"
opts = subset.Options()
opts.flavor = "woff2"
opts.layout_features = ["*"]
font = subset.load_font("build/NotoSansJP.ttf", opts)
sub = subset.Subsetter(opts)
sub.populate(text=text)
sub.subset(font)
subset.save_font(font, "src/fonts/kana.woff2", opts)
print("font", os.path.getsize("src/fonts/kana.woff2"), "bytes")
